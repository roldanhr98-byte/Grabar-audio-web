// Firma: si existen secretos (CI) se usa el keystore de release; si no, el keystore
// de depuración incluido en el repositorio para que todas las compilaciones
// tengan la misma firma y la APK pueda actualizarse sin desinstalar.
val releaseKeystoreB64: String? = System.getenv("ANDROID_KEYSTORE_BASE64")
val releaseKeystoreFile = layout.buildDirectory.file("release.keystore").get().asFile

val versionCodeEnv = System.getenv("VERSION_CODE")?.toIntOrNull() ?: 1

android {
    namespace = "com.audiovault.browser"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.audiovault.browser"
        minSdk = 26
        targetSdk = 35
        versionCode = versionCodeEnv
        versionName = "1.0.$versionCodeEnv"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables { useSupportLibrary = true }
    }

    signingConfigs {
        getByName("debug") {
            storeFile = file("audiovault-debug.keystore")
            storePassword = "android"
            keyAlias = "androiddebugkey"
            keyPassword = "android"
        }
        create("release") {
            if (!releaseKeystoreB64.isNullOrBlank()) {
                releaseKeystoreFile.parentFile.mkdirs()
                releaseKeystoreFile.writeBytes(Base64.getDecoder().decode(releaseKeystoreB64.trim()))
                storeFile = releaseKeystoreFile
                storePassword = System.getenv("ANDROID_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("ANDROID_KEY_ALIAS")
                keyPassword = System.getenv("ANDROID_KEY_PASSWORD")
            } else {
                storeFile = file("audiovault-debug.keystore")
                storePassword = "android"
                keyAlias = "androiddebugkey"
                keyPassword = "android"
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.getByName("release")
        }
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
            signingConfig = signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
    testOptions {
        unitTests.isReturnDefaultValues = true
    }
    lint {
        abortOnError = false
        checkReleaseBuilds = false
    }
}

